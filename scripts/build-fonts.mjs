// Writes src/styles/fonts.css and copies the font files to public/fonts/.
//  - Noto Sans JP latin subset (fontsource) for weights 400, 600, 700
//  - one Japanese subset (700) with only the characters the site uses,
//    committed at src/assets/fonts/ (rebuild with scripts/make_ja_font.py)
// Fails the build if the source uses a Japanese character the subset lacks.
import fs from 'node:fs';
import path from 'node:path';

const PKG = 'node_modules/@fontsource/noto-sans-jp/files';
const OUT = 'public/fonts';
const JA = 'src/assets/fonts/noto-sans-jp-ja-700.woff2';
const JA_CHARS = 'src/assets/fonts/ja-chars.txt';

const used = new Set();
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(astro|md|mjs|ts)$/.test(f)) for (const ch of fs.readFileSync(p, 'utf8')) if (/[　-鿿＀-￯]/.test(ch)) used.add(ch);
  }
})('src');
const have = new Set(fs.readFileSync(JA_CHARS, 'utf8'));
const missing = [...used].filter((c) => !have.has(c));
if (missing.length) {
  console.error(`✗ Japanese characters missing from the subset font: ${missing.join('')}\n  Run: python3 scripts/make_ja_font.py /path/to/NotoSansJP-Bold.ttf`);
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const latinRange = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2190-2199,U+2212,U+2215,U+FEFF,U+FFFD';
let css = '/* Generated by scripts/build-fonts.mjs. Do not edit. Noto Sans JP, SIL Open Font License. */\n';
for (const w of [400, 600, 700]) {
  const f = `noto-sans-jp-latin-${w}-normal.woff2`;
  fs.copyFileSync(`${PKG}/${f}`, `${OUT}/${f}`);
  css += `@font-face{font-family:'Noto Sans JP';font-style:normal;font-weight:${w};font-display:swap;src:url('/fonts/${f}') format('woff2');unicode-range:${latinRange}}\n`;
}
fs.copyFileSync(JA, `${OUT}/noto-sans-jp-ja-700.woff2`);
const jaRange = [...have].map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase()).join(',');
css += `@font-face{font-family:'Noto Sans JP';font-style:normal;font-weight:700;font-display:swap;src:url('/fonts/noto-sans-jp-ja-700.woff2') format('woff2');unicode-range:${jaRange}}\n`;
fs.writeFileSync('src/styles/fonts.css', css);
console.log(`fonts: ${used.size} Japanese characters covered by a ${Math.round(fs.statSync(JA).size / 1024)} KB subset; 3 latin weights`);
