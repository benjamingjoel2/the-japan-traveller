// Writes src/styles/fonts.css and copies font files to public/fonts/.
//  - Inter 400/500 (text) and Shippori Mincho 500 (headings), latin subsets
//  - one Shippori Mincho 500 subset with only the Japanese characters the site
//    uses, committed at src/assets/fonts/ (rebuild with scripts/make_ja_font.py)
// Fails the build if the source uses a Japanese character the subset lacks.
import fs from 'node:fs';
import path from 'node:path';

const JA = 'src/assets/fonts/shippori-mincho-ja-500.woff2';
const JA_CHARS = 'src/assets/fonts/ja-chars.txt';
const used = new Set();
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(astro|md|mjs|ts)$/.test(f)) for (const ch of fs.readFileSync(p, 'utf8')) if (/[　-鿿＀-￯]/.test(ch)) used.add(ch);
  }
})('src');
const have = new Set(fs.existsSync(JA_CHARS) ? fs.readFileSync(JA_CHARS, 'utf8') : '');
const missing = [...used].filter((c) => !have.has(c));
if (missing.length || !fs.existsSync(JA)) {
  console.error(`✗ Japanese characters missing from the subset font: ${missing.join('')}\n  Run: python3 scripts/make_ja_font.py /path/to/ShipporiMincho-Medium.ttf`);
  process.exit(1);
}

const OUT = 'public/fonts';
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const latin = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2190-2199,U+2212,U+2215,U+FEFF,U+FFFD';
const faces = [
  ['Inter', 400, 'node_modules/@fontsource/inter/files/inter-latin-400-normal.woff2', latin],
  ['Inter', 500, 'node_modules/@fontsource/inter/files/inter-latin-500-normal.woff2', latin],
  ['Shippori Mincho', 500, 'node_modules/@fontsource/shippori-mincho/files/shippori-mincho-latin-500-normal.woff2', latin],
  ['Shippori Mincho', 500, JA, [...have].map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase()).join(',')],
];
let css = '/* Generated by scripts/build-fonts.mjs. Do not edit. Inter and Shippori Mincho, SIL Open Font License. */\n';
for (const [fam, w, src, range] of faces) {
  const name = path.basename(src);
  fs.copyFileSync(src, `${OUT}/${name}`);
  css += `@font-face{font-family:'${fam}';font-style:normal;font-weight:${w};font-display:swap;src:url('/fonts/${name}') format('woff2');unicode-range:${range}}\n`;
}
fs.writeFileSync('src/styles/fonts.css', css);
console.log(`fonts: Inter 400/500, Shippori Mincho 500; ${used.size} Japanese characters in a ${Math.round(fs.statSync(JA).size / 1024)} KB subset`);
